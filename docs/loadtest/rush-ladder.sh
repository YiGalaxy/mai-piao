#!/bin/bash
# ============================================================
# 一组规模递增的抢购压测，结果追加到 results.txt。
#
# 每一级都是一场全新的场次，所以数字之间可比：同样是 2000 个座位、
# 同样是四个票档，只是买家一次比一次多。
#
#   ./rush-ladder.sh [threads] [buyer1 buyer2 ...]
#
# 做成一梯次而不是一次大压测，是为了看出系统从哪里开始跟不上。
# 一个数字只能告诉你成没成；一串数字才能告诉你代价有多大。
# ============================================================
set -u

DIR="$(cd "$(dirname "$0")" && pwd)"
THREADS="${1:-200}"
shift || true
BUYERS="${*:-500 1000 3000 6000}"

OUT="$DIR/results.txt"
{
  echo "============================================================"
  echo "压测 $(date '+%Y-%m-%d %H:%M:%S')  并发=$THREADS  买家序列=$BUYERS"
  echo "============================================================"
} >> "$OUT"

for N in $BUYERS; do
  echo
  echo "########## 买家 $N ##########"
  bash "$DIR/run-rush.sh" "$N" "$THREADS" queue 2>&1 \
    | iconv -f utf-8 -t utf-8 -c \
    | tee -a "$OUT"
done

echo
echo "完整结果已写入 $OUT"
